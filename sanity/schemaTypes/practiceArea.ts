import { defineField, defineType } from 'sanity';

export default defineType({
  name: 'practiceArea',
  title: 'Practice Area',
  type: 'document',
  groups: [
    { name: 'content', title: 'Content' },
    { name: 'seo', title: 'SEO & AI Visibility' },
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      group: 'content',
      description: 'e.g. "Personal Injury"',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'URL Slug',
      type: 'slug',
      group: 'content',
      description: 'Keep this matching your current live URL where possible (e.g. "injury") to preserve existing SEO rankings.',
      options: { source: 'title', maxLength: 96 },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'isFree',
      title: 'Is this a free-referral practice area?',
      type: 'boolean',
      group: 'content',
      description: 'Turn off for Criminal Defense / Family Law, where attorneys charge a fee, per your current site copy.',
      initialValue: true,
    }),
    defineField({
      name: 'heroHeadline',
      title: 'Hero Headline',
      type: 'string',
      group: 'content',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'heroSubhead',
      title: 'Hero Subheadline',
      type: 'text',
      rows: 3,
      group: 'content',
    }),
    defineField({
      name: 'videoUrl',
      title: 'Explainer Video URL (optional)',
      type: 'url',
      group: 'content',
    }),
    defineField({
      name: 'body',
      title: 'Main Content',
      type: 'array',
      group: 'content',
      description: 'The full, comprehensive explanation of this practice area. Write this to genuinely answer every question someone in this situation would have — depth here is what builds topical authority with both search engines and AI systems.',
      of: [
        { type: 'block' },
        { type: 'image', options: { hotspot: true } },
      ],
    }),
    defineField({
      name: 'faqs',
      title: 'Frequently Asked Questions',
      type: 'array',
      group: 'content',
      description: 'Directly answer real questions people search for. This powers FAQPage structured data, which both Google and AI answer engines pull from directly.',
      of: [{ type: 'reference', to: [{ type: 'faq' }] }],
    }),
    defineField({
      name: 'relatedPosts',
      title: 'Related Blog Posts',
      type: 'array',
      group: 'content',
      of: [{ type: 'reference', to: [{ type: 'post' }] }],
    }),
    defineField({
      name: 'seoTitle',
      title: 'SEO Title Tag',
      type: 'string',
      group: 'seo',
      validation: (Rule) => Rule.max(60).warning('Keep under 60 characters so it doesn\'t get truncated in search results.'),
    }),
    defineField({
      name: 'seoDescription',
      title: 'Meta Description',
      type: 'text',
      rows: 2,
      group: 'seo',
      validation: (Rule) => Rule.max(160).warning('Keep under 160 characters.'),
    }),
    defineField({
      name: 'seoKeywords',
      title: 'Target Keywords / Topics',
      type: 'array',
      group: 'seo',
      of: [{ type: 'string' }],
      options: { layout: 'tags' },
    }),
  ],
  preview: {
    select: { title: 'title', subtitle: 'slug.current' },
  },
});
